"""Innodata (INOD) DCF (personal, not for the Wharton competition; 23 Nov 2026).

    python personal/innodata_dcf.py    # writes personal/innodata_valuation_2026-11-23.md

Innodata sells AI training data and data engineering: few physical assets, so a standard FCFF DCF fits
(unlike CoreWeave's capacity model). FCFF = EBIT(1 - t) + D&A - capex - 12% of the revenue increase (working capital).
Balance sheet at 30 Sep 2026; cash flows from Q4 2026; terminal growth 3%. Scenario inputs are my
assumptions (ASSUMPTION); company figures are RESEARCH (Yahoo statements, Q3 2026 results).
"""
from pathlib import Path

PRICE = 32.75            # $, Yahoo 23 Nov 2026
SHARES = 35.62           # m, Q3 2026 diluted average (34.38m outstanding + options and RSUs)
CASH = 154.0             # $m, cash 164 at 30 Sep 2026 less customer prepayments (company, Q3 2026 results); no debt
REV_2025, REV_9M = 251.66, 277.86          # $m: FY2025; Q1-Q3 2026 actual (90.10 + 92.14 + 95.62)
REV_2026 = REV_2025 * 1.42                 # guidance: 2026 growth of 42% or more (Q4 absorbs a ~$12m program wind-down)
TAX, DA, CAPEX, NWC = 0.22, 0.024, 0.027, 0.12   # 2025 effective tax 22.3%; D&A and capex % of revenue (2025-26); receivables ~12% of revenue
G, Y0, LAST = 0.03, 0.10, 2035
Q4_MARGIN = 0.09                           # Q3 2026 operating margin 9.0% (gross margin fell to 37%)

SCEN = {
    "Bear": dict(growth=[-0.10, 0.05], margin=0.08,
                 story="One of the two big customers (73% of revenue together) cuts work in 2027; growth then only 3-5%; margins stay at Q3's level"),
    "Base": dict(growth=[0.24, 0.18, 0.14, 0.10], margin=0.14,
                 story="2027 near the (March 2026) consensus $442m; growth slows to 3% by 2035; GAAP operating margin 14% (9 months of 2026: 14.9%)"),
    "Bull": dict(growth=[0.35, 0.28, 0.22, 0.16], margin=0.20,
                 story="New hyperscaler and physical-AI programs keep growth high; scale lifts the margin to 20%"),
}


def revenue(growth):
    rev, y = {2026: REV_2026}, 2027
    for g in growth:
        rev[y] = rev[y - 1] * (1 + g)
        y += 1
    g0, first = growth[-1], y
    while y <= LAST + 1:
        g = G if y > LAST else g0 + (G - g0) * (y - first + 1) / (LAST - first + 1)
        rev[y] = rev[y - 1] * (1 + g)
        y += 1
    return rev


def value(s, margin=None, wacc=0.12, growth=None):
    m = s["margin"] if margin is None else margin
    rev = revenue(growth or s["growth"])
    q4 = REV_2026 - REV_9M
    q3 = 95.62                                             # receivables follow the annualized quarterly run rate (Q3 -> Q4)
    fcff = q4 * Q4_MARGIN * (1 - TAX) + q4 * (DA - CAPEX) - NWC * 4 * (q4 - q3)
    pv = fcff / (1 + wacc) ** Y0
    rows = []
    for t in range(2027, LAST + 1):
        f = rev[t] * m * (1 - TAX) + rev[t] * (DA - CAPEX) - NWC * (rev[t] - rev[t - 1])
        pv += f / (1 + wacc) ** (Y0 + t - 2026)
        rows.append((t, rev[t], f))
    f_tv = rev[LAST + 1] * m * (1 - TAX) + rev[LAST + 1] * (DA - CAPEX) - NWC * (rev[LAST + 1] - rev[LAST])
    pv_tv = f_tv / (wacc - G) / (1 + wacc) ** (Y0 + LAST - 2026)
    ev = pv + pv_tv
    return dict(ev=ev, pv_tv=pv_tv, ps=(ev + CASH) / SHARES, rows=rows, rev=rev)


def solve_growth(target):
    """One growth rate for 2027-2030 (then the fade), base margin and 12%, that gives today's price."""
    lo, hi = -0.3, 1.5
    for _ in range(60):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if value(SCEN["Base"], growth=[mid] * 4)["ps"] < target else (lo, mid)
    return (lo + hi) / 2


