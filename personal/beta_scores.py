"""Innodata and CoreWeave against our strategy, the winner's, and the DCFs at each beta (personal; 23 Nov 2026).

    python personal/beta_scores.py    # writes personal/beta_scores_2026-11-23.md

Discount rate from a beta, the way the Round 2 method builds it (m03.run.wacc_for): cost of equity = 4.94% + beta x 5%;
CoreWeave also has debt: market weights (equity $27.2bn, debt and finance leases $47.5bn) and a 9.5% pre-tax
cost of debt (Q4 2026 interest guidance on about $47bn), taxed at 21%. Innodata has no debt.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import coreweave_dcf as cw  # noqa: E402
import innodata_dcf as ino  # noqa: E402

RF, ERP = 0.0494, 0.05
E_CW, D_CW, KD_CW = cw.PRICE * cw.SHARES / 1000, cw.DEBT + cw.FIN_LEASES, 0.095


def wacc_cw(beta):
    w = E_CW / (E_CW + D_CW)
    return w * (RF + beta * ERP) + (1 - w) * KD_CW * (1 - cw.TAX)


SCREEN = [  # 60 monthly USD returns to Oct 2026 vs ACWI, T-bill adjusted (tools/refined_screen.py); averages from the 17 Nov universe screen
    ("Innodata", "66.6%", "2.86", "Industrials 3.5% / 1.11 (IT 7.7% / 1.26)", "fail", "fail (alpha above, beta above)"),
    ("CoreWeave", "-37.8% (18 months)", "7.99 (18 months)", "not verified", "not screenable (60 months needed)", "not screenable"),
]
BETAS_INOD = [("1.00 (market)", 1.0), ("1.52 (full history since 1993, vs SPY)", 1.52), ("3.12 (5 years, vs SPY)", 3.12)]
BETAS_CW = [("1.00 (market)", 1.0), ("1.97 (S&P 500 semiconductors average)", 1.97), ("7.65 (19 months since listing, vs SPY)", 7.65)]


def main():
    L = ["# Innodata and CoreWeave: our strategy, the winner's, and the DCFs at each beta (personal, 23 Nov 2026)", "",
         "Not for the Wharton competition. Generated by `python personal/beta_scores.py`.", "",
         "## 1. The screen (60 monthly returns to Oct 2026 vs ACWI)", "",
         "| | Alpha | Beta | Industry alpha / beta | Ours (beta below) | Winner's (alpha above and beta below) |", "|---|---|---|---|---|---|"]
    L += [f"| {' | '.join(r)} |" for r in SCREEN]
    L += ["", "## 2. Standard Round 2 DCF (`python tools/round2_team.py inod` and `ai6`)", "",
          "| | Price | Value / price at beta 1.0 | at 5-year beta | at full-history beta | Bear / price | Tests 2 and 3 |", "|---|---|---|---|---|---|---|",
          "| Innodata | 32.84 | 0.98 | 0.44 (3.12) | 0.74 (1.52) | 0.47 | fail, fail |",
          "| CoreWeave | 49.06 | negative | negative (7.65) | negative (7.65) | negative | fail, fail (method holds capex at 201% of revenue) |", "",
          "## 3. The personal DCFs at each beta ($ per share)", "", "**Innodata** (no debt, so the discount rate is the cost of equity):", "",
          "| Beta | Discount rate | Bear | Base | Bull |", "|---|---|---|---|---|"]
    for lab, b in BETAS_INOD:
        k = RF + b * ERP
        L.append(f"| {lab} | {k:.1%} | " + " | ".join(f"${ino.value(s, wacc=k)['ps']:.2f}" for s in ino.SCEN.values()) + " |")
    L += [f"| Model default | 12.0% | " + " | ".join(f"${ino.value(s)['ps']:.2f}" for s in ino.SCEN.values()) + " |",
          "", f"Price ${ino.PRICE:.2f}.", "", "**CoreWeave** (capacity DCF; WACC from the beta at today's market weights):", "",
          "| Beta | WACC | Bear | Base | Bull |", "|---|---|---|---|---|"]
    for lab, b in BETAS_CW:
        w = wacc_cw(b)
        L.append(f"| {lab} | {w:.1%} | " + " | ".join(f"${cw.value(s, wacc_const=w)['ps']:,.0f}" for s in cw.SCEN.values()) + " |")
    L += ["| Model default (12% to 2031, then 9.5%) | path | " + " | ".join(f"${cw.value(s)['ps']:,.0f}" for s in cw.SCEN.values()) + " |",
          "", f"Price ${cw.PRICE:.2f}. A negative value means the business is worth less than its debt (the shares would be worth only their option value).", ""]
    Path(__file__).with_name("beta_scores_2026-11-23.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
