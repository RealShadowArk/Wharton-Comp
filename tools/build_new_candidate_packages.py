def subset(src, keep, dst):
    wb = openpyxl.load_workbook(src)
    extra = {"Start here", "Where to find it", "Evidence", "MISSING", "Coverage", "Provisional evidence", "Research coverage"}
    tickers = {str(r[1]) for t in keep for r in wb[t].iter_rows(min_row=2, values_only=True) if r[1]}
    for ws in list(wb.worksheets):
        if ws.title not in keep and ws.title not in extra:
            wb.remove(ws)
        elif ws.title in extra and str(ws["A1"].value).lower() == "ticker":
            for i in range(ws.max_row, 1, -1):  # keep only this group's evidence rows
                v = ws.cell(i, 1).value
                if v not in (None, "") and str(v) not in tickers:
                    ws.delete_rows(i)
    wb.save(dst)


