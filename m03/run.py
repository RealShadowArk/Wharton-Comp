"""Run an M03 DCF from inputs/m03/<TICKER>_dcf_inputs.csv.

Usage: python -m m03.run HUBB   (writes outputs/M03_Valuation_<TICKER>.md and .csv)
"""

import csv
import sys
from pathlib import Path

from m03.dcf import (Inputs, grid, implied_growth_shift, sensitivity, value,
                     wacc)

ROOT = Path(__file__).resolve().parent.parent
TUPLES = ("growth", "ebit_margin", "da_pct", "capex_pct")
FIELDS = ("base_revenue", "tax_rate", "nwc_pct_of_change", "terminal_growth",
          "debt", "non_operating_assets", "diluted_shares",
          "years_to_first_cash_flow")


def load(ticker):
    path = ROOT / "inputs" / "m03" / f"{ticker}_dcf_inputs.csv"
    with open(path, encoding="utf-8") as f:
        rows = {r["field"]: r for r in csv.DictReader(f)}
    raw = {k: r["value"] for k, r in rows.items()}
    k_wacc = wacc(float(raw["risk_free"]), float(raw["beta"]),
                  float(raw["equity_premium"]), float(raw["pre_tax_cost_of_debt"]),
                  float(raw["tax_rate"]), float(raw["equity_value_for_weights"]),
                  float(raw["debt_value_for_weights"]))
    kw = {k: tuple(float(x) for x in raw[k].split(";")) for k in TUPLES}
    kw.update({k: float(raw[k]) for k in FIELDS})
    if raw.get("terminal_reinvestment_rate"):
        kw["terminal_reinvestment_rate"] = float(raw["terminal_reinvestment_rate"])
    return Inputs(wacc=k_wacc, **kw), raw, rows


def fmt(x, pct=False):
    if x is None:
        return "NOT DEFINED"
    return f"{x:.1%}" if pct else f"{x:,.0f}"


def run(ticker):
    p, raw, rows = load(ticker)
    price = float(raw["price"])
    v = value(p)
    first_year = int(raw["base_year"]) + 1
    out = ROOT / "outputs"
    with open(out / f"M03_Valuation_{ticker}.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["year", "revenue", "ebit", "nopat", "da", "capex", "d_nwc",
                    "fcff", "discount_factor", "pv_fcff"])
        for r in v["rows"]:
            w.writerow([first_year + r["year"] - 1] + [round(r[k], 2) for k in
                       ("revenue", "ebit", "nopat", "da", "capex", "d_nwc",
                        "fcff", "discount_factor", "pv_fcff")])

    shift = implied_growth_shift(p, price)
    waccs = [round(p.wacc + d, 4) for d in (-0.01, -0.005, 0, 0.005, 0.01)]
    gs = [0.02, 0.025, 0.03, 0.035, 0.04]
    margins = [-0.03, -0.015, 0, 0.015, 0.03]
    g_tab = grid(p, "wacc", waccs, "terminal_growth", gs)
    m_tab = {w_: sensitivity(Inputs(**{**p.__dict__, "wacc": w_}), "ebit_margin", margins)
             for w_ in waccs}

    L = [f"# M03 valuation: {ticker} (DCF, FCFF at WACC)", "",
         f"Valuation date {raw['valuation_date']}. Generated by `python -m m03.run {ticker}` "
         f"from `inputs/m03/{ticker}_dcf_inputs.csv`, where every input carries its label "
         "and source. A DCF value is a research estimate under stated assumptions: never a "
         "price target, an annual return or a position size.", "",
         "## Result", "",
         "| Item | Value |", "|---|---|",
         f"| WACC | {p.wacc:.2%} |",
         f"| Terminal growth | {p.terminal_growth:.1%} |",
         f"| Enterprise value (USD m) | {fmt(v['ev'])} |",
         f"| of which terminal value | {v['terminal_share_of_ev']:.0%} |",
         f"| + cash, - debt (USD m) | {fmt(p.non_operating_assets)} / {fmt(p.debt)} |",
         f"| Equity value (USD m) | {fmt(v['equity'])} |",
         f"| **Value per diluted share** | **${v['per_share']:,.2f}** |",
         f"| Price used | ${price:,.2f} ({rows['price']['source']}) |",
         f"| Value / price | {v['per_share'] / price:.2f} |", "",
         "## What the price assumes (reverse DCF)", ""]
    if shift is None:
        L.append("No growth shift within +/-50 points matches the price.")
    else:
        implied = [g + shift for g in p.growth]
        L.append(f"Holding margins, reinvestment and WACC fixed, the price matches the DCF "
                 f"if every forecast-year revenue growth rate is shifted by {shift:+.1%}: "
                 + ", ".join(f"{first_year + i}: {g:.1%}" for i, g in enumerate(implied))
                 + f" (base case: " + ", ".join(f"{g:.0%}" for g in p.growth) + ").")
    L += ["", "## Forecast (USD m)", "",
          "| Year | Revenue | EBIT | NOPAT | D&A | Capex | ΔNWC | FCFF | PV |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in v["rows"]:
        L.append(f"| {first_year + r['year'] - 1} | " + " | ".join(
            fmt(r[k]) for k in ("revenue", "ebit", "nopat", "da", "capex", "d_nwc",
                                "fcff", "pv_fcff")) + " |")
    L.append(f"| Terminal | | | | | | | FCFF {fmt(v['fcff_next'])} | "
             f"{fmt(v['pv_terminal'])} |")
    L += ["", "## Sensitivity 1: WACC (rows) x terminal growth (columns), $ per share", "",
          "| WACC | " + " | ".join(f"g {g:.1%}" for g in gs) + " |",
          "|---" * (len(gs) + 1) + "|"]
    for w_, row in g_tab.items():
        L.append(f"| {w_:.2%} | " + " | ".join(
            "NOT DEFINED" if x is None else f"${x:,.0f}" for x in row.values()) + " |")
    L += ["", "## Sensitivity 2 (operating driver): WACC x EBIT margin change, $ per share", "",
          "| WACC | " + " | ".join(f"margin {m:+.1%}" for m in margins) + " |",
          "|---" * (len(margins) + 1) + "|"]
    for w_, row in m_tab.items():
        L.append(f"| {w_:.2%} | " + " | ".join(f"${x:,.0f}" for x in row.values()) + " |")
    L += ["", "## Inputs", "", "| Input | Value | Label | Source | Note |",
          "|---|---|---|---|---|"]
    for k, r in rows.items():
        L.append(f"| {k} | {r['value']} | {r['label']} | {r['source']} | {r['note']} |")
    (out / f"M03_Valuation_{ticker}.md").write_text("\n".join(L) + "\n")
    return p, v, shift, price


if __name__ == "__main__":
    p, v, shift, price = run(sys.argv[1] if len(sys.argv) > 1 else "HUBB")
    print(f"WACC {p.wacc:.2%}  value/share {v['per_share']:.2f}  price {price}  "
          f"TV share {v['terminal_share_of_ev']:.0%}  implied growth shift "
          f"{'n/a' if shift is None else f'{shift:+.2%}'}")
